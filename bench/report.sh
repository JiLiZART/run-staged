#!/usr/bin/env bash
# Render bench/results/ (from run.sh) as markdown on stdout.
set -euo pipefail

RESULTS=${1:-$(cd "$(dirname "$0")" && pwd)/results}

cpu() {
  sysctl -n machdep.cpu.brand_string 2>/dev/null || lscpu 2>/dev/null | sed -n 's/^Model name: *//p'
}
cores() {
  sysctl -n hw.ncpu 2>/dev/null || nproc
}

# table <json>: mean ± σ, min, max, relative to run-staged (or the fastest when it wasn't run).
table() {
  jq -r '
    .results | sort_by(.mean) as $r
    | (($r | map(select(.command == "run-staged"))[0]) // $r[0]).mean as $base
    | "| Tool | Mean [ms] | Min [ms] | Max [ms] | Relative |",
      "|:---|---:|---:|---:|---:|",
      ($r[] | "| \(.command) | \(.mean * 1000 | round) ± \(.stddev * 1000 | round) | \(.min * 1000 | round) | \(.max * 1000 | round) | \(.mean / $base * 100 | round / 100)x |")
  ' "$1"
}

# 4 tasks x 0.5 s: ideal parallel 0.5 s, sequential 2.0 s.
concurrency_table() {
  jq -r '
    "| Tool | Mean [s] | Ideal [s] | Sequential [s] | Parallelism | Mode |",
    "|:---|---:|---:|---:|---:|:---|",
    (.results | sort_by(.mean)[] | (2.0 / .mean) as $p
      | "| \(.command) | \(.mean * 100 | round / 100) | 0.50 | 2.00 | \($p * 10 | round / 10)x | \(if $p < 1.3 then "sequential" else "parallel" end) |")
  ' "$1"
}

cat <<EOF
# Benchmark results

Generated by \`bench/run.sh\` on $(date -u +%Y-%m-%d).

- OS: $(uname -srm)
- CPU: $(cpu) ($(cores) cores)

## Tool versions

| Tool | Version |
|:---|:---|
$(awk -F'\t' '{printf "| %s | %s |\n", $1, $2}' "$RESULTS/versions.tsv")
EOF

section() {
  [[ -f $RESULTS/$1.json ]] || return 0
  printf '\n## %s\n\n%s\n\n' "$2" "$3"
  table "$RESULTS/$1.json"
}

section overhead "Overhead" "No-op command on 100 staged files: the tool's own startup, git and matching cost."

if compgen -G "$RESULTS/scaling-*.json" >/dev/null; then
  printf '\n## Scaling\n\nOverhead scenario across staged file counts.\n'
  for f in $(printf '%s\n' "$RESULTS"/scaling-*.json | sort -V); do
    n=${f##*/scaling-}
    printf '\n### %s files\n\n' "${n%.json}"
    table "$f"
  done
fi

if [[ -f $RESULTS/concurrency.json ]]; then
  printf '\n## Concurrency\n\n4 tasks on disjoint globs, each sleeping 0.5 s. Parallelism = sequential time / measured time.\n\n'
  concurrency_table "$RESULTS/concurrency.json"
fi

section partial-staging "Partial staging" "100 staged files that also carry unstaged edits; each tool in its default mode."
if [[ -f $RESULTS/unstaged.tsv ]]; then
  printf '\n"Hides unstaged" = commands never saw the unstaged edits. "Preserved" = edits still in the working tree afterwards.\n\n'
  printf '| Tool | Hides unstaged | Preserved |\n|:---|:---|:---|\n'
  awk -F'\t' '{printf "| %s | %s | %s |\n", $1, $2, ($3 == "yes" ? "yes" : "**NO - lost**")}' "$RESULTS/unstaged.tsv"
fi

if [[ -s $RESULTS/failures.tsv ]]; then
  printf '\n## Failures\n\nTools that exited non-zero on their untimed first run and were left out of that scenario.\n\n'
  printf '| Scenario | Tool | Last output line |\n|:---|:---|:---|\n'
  awk -F'\t' '{gsub(/\|/, "\\|", $3); printf "| %s | %s | `%s` |\n", $1, $2, $3}' "$RESULTS/failures.tsv"
fi
